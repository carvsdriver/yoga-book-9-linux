#!/usr/bin/env bash
# rebuild-patches.sh — Rebuild and reinstall hid-multitouch, cdc-acm,
# yb9-kbdock, and lenovo-ymc kernel patches for the running kernel.
# Also reinstalls the screen rotation daemon and udev rules.
#
# Patches applied:
#   0001  hid-multitouch  — Yoga Book 9 touchscreen descriptor fixup
#   0002  hid-multitouch  — Fix stale MT slots when contact count drops to zero
#   0003  hid-multitouch  — Suppress cycling ghost contacts (INGENIC firmware bug)
#   0004  cdc-acm         — INGENIC 17EF:6161 quirk (VENDOR_CLASS_DATA_IFACE +
#                           ALWAYS_POLL_CTRL)
#   0005  cdc-acm         — start bulk-IN polling when ALWAYS_POLL_CTRL is set
#   0006  yb9-kbdock      — keyboard dock detection driver (new file; sourced
#                           from sources/lenovo-yb9-kbdock.c; local build
#                           adaptation of ~/drivers/yb9-kbdock-submission)
#   0007  lenovo-ymc      — return -ENODEV on Yoga Book 9 (yb9-kbdock owns
#                           SW_TABLET_MODE on this hardware); generated from
#                           ~/kernel-upstream/hid branch lenovo-ymc-yb9-v13
#
# Upstream submission: v15 patches in ~/projects/yoga9ibook/kernel/upstream/v15/
#   (generated by git format-patch from ~/drivers/yb9-kbdock-submission squashed commit).
#   Message-ID: <20260728225545.1333610-1-carvsdriver@gmail.com>
#
# Rotation (step 15, no kernel build needed):
#   61-sensor-yogabook9.rules  → /etc/udev/rules.d/   (accel mount matrix fix)
#   51-sensor-proxy-yoga9.rules → /etc/polkit-1/rules.d/
#   yoga9-rotate.py            → /usr/local/bin/
#   screen-rotate.service      → /etc/systemd/system/
#
# Usage:
#   cd ~/projects/yoga9ibook/kernel
#   bash rebuild-patches.sh

set -euo pipefail

KVER="$(uname -r)"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(dirname "${SCRIPT_DIR}")"
BUILD_DIR="${HOME}/kernel-src"
RPM_CACHE="${HOME}/kernel-src-rpms"

HID_PATCH="${SCRIPT_DIR}/patches/0001-HID-multitouch-Fix-Yoga-Book-9-14IAH10-touchscreen-m.patch"
HID_PATCH2="${SCRIPT_DIR}/patches/0002-HID-multitouch-Fix-stale-MT-slots-when-contact-count-drops-to-zero.patch"
HID_PATCH3="${SCRIPT_DIR}/patches/0003-HID-multitouch-Suppress-cycling-ghost-contacts-for-Yoga-Book-9.patch"
CDC_PATCH="${SCRIPT_DIR}/patches/0004-USB-CDC-ACM-add-INGENIC-17EF-6161-quirk-for-Yoga-Book-9.patch"
CDC_PATCH3="${SCRIPT_DIR}/patches/0005-USB-cdc-acm-ALWAYS_POLL_CTRL-also-poll-bulk-IN.patch"
KBDOCK_SRC="${SCRIPT_DIR}/sources/lenovo-yb9-kbdock.c"
YMC_PATCH="${SCRIPT_DIR}/patches/0007-platform-x86-lenovo-lenovo-ymc-Skip-Yoga-Book-9.patch"

echo "==> Rebuilding patches for kernel ${KVER}"

# --------------------------------------------------------------------------
# 1. Build prerequisites
# --------------------------------------------------------------------------
echo "==> Installing build prerequisites..."
sudo dnf install -y rpm-build zstd
if ! rpm -q "kernel-devel-${KVER}" &>/dev/null; then
    echo "==> kernel-devel-${KVER} not installed; attempting dnf install..."
    # Strip arch suffix (.x86_64) for dnf name resolution
    sudo dnf install -y "kernel-devel-${KVER%.*}" || \
        echo "    WARNING: kernel-devel not found in repos — build will use existing /usr/src/kernels/${KVER}"
fi

# --------------------------------------------------------------------------
# 2. Download source RPM (cached by kernel version)
# --------------------------------------------------------------------------
KVER_NVR="kernel-${KVER%.*}"   # e.g. kernel-6.19.12-200.fc43

mkdir -p "${RPM_CACHE}"
SRC_RPM_GLOB="${RPM_CACHE}/${KVER_NVR}.src.rpm"

if ! ls ${SRC_RPM_GLOB} &>/dev/null; then
    echo "==> Downloading kernel source RPM (${KVER_NVR})..."
    pushd "${RPM_CACHE}" >/dev/null
    if ! dnf download --source "${KVER_NVR}" 2>/dev/null; then
        echo "    dnf download unavailable; falling back to koji..."
        if ! command -v koji &>/dev/null; then
            sudo dnf install -y koji
        fi
        koji download-build --arch=src "${KVER_NVR}"
    fi
    popd >/dev/null
else
    echo "==> Source RPM already cached: $(ls ${SRC_RPM_GLOB})"
fi

SRC_RPM="$(ls ${SRC_RPM_GLOB})"

# --------------------------------------------------------------------------
# 3. Extract kernel tarball from RPM (cached per kernel version)
# --------------------------------------------------------------------------
TARBALL_DIR="${RPM_CACHE}"
KVER_BASE="$(echo "${KVER}" | grep -oP '^\d+\.\d+\.\d+')"   # e.g. 7.0.6

if ! ls "${TARBALL_DIR}"/linux-${KVER_BASE}*.tar.xz &>/dev/null; then
    echo "==> Extracting source tarball from RPM..."
    pushd "${TARBALL_DIR}" >/dev/null
    rpm2cpio "${SRC_RPM}" | cpio -idmv '*.tar.xz' 2>/dev/null
    popd >/dev/null
fi

TARBALL="$(ls "${TARBALL_DIR}"/linux-${KVER_BASE}*.tar.xz 2>/dev/null | head -1)"
if [ -z "${TARBALL}" ]; then
    echo "ERROR: no source tarball for ${KVER_BASE} found in ${TARBALL_DIR}" >&2
    exit 1
fi
KVER_SRC="$(basename "${TARBALL}" | grep -oP 'linux-\K[0-9.]+(?=\.tar)')"
echo "==> Source tarball: linux-${KVER_SRC}.tar.xz"

# --------------------------------------------------------------------------
# 4. Set up build directory with fresh driver sources
# --------------------------------------------------------------------------
echo "==> Extracting fresh driver sources into ${BUILD_DIR}..."
mkdir -p "${BUILD_DIR}"

tar xf "${TARBALL}" --strip-components=3 -C "${BUILD_DIR}" \
    "linux-${KVER_SRC}/drivers/hid/hid-multitouch.c" \
    "linux-${KVER_SRC}/drivers/hid/hid-ids.h" \
    "linux-${KVER_SRC}/drivers/hid/hid-haptic.h"

tar xf "${TARBALL}" --strip-components=4 -C "${BUILD_DIR}" \
    "linux-${KVER_SRC}/drivers/usb/class/cdc-acm.c" \
    "linux-${KVER_SRC}/drivers/usb/class/cdc-acm.h"

tar xf "${TARBALL}" --strip-components=5 -C "${BUILD_DIR}" \
    "linux-${KVER_SRC}/drivers/platform/x86/lenovo/ymc.c" \
    "linux-${KVER_SRC}/drivers/platform/x86/lenovo/ideapad-laptop.h"

# yb9-kbdock is a new driver not present in the upstream tree; copy from here.
cp "${KBDOCK_SRC}" "${BUILD_DIR}/yb9-kbdock.c"

# --------------------------------------------------------------------------
# 5. Write Makefile
# --------------------------------------------------------------------------
cat > "${BUILD_DIR}/Makefile" << 'EOF'
obj-m := hid-multitouch.o cdc-acm.o yb9-kbdock.o lenovo-ymc.o
lenovo-ymc-y := ymc.o
EOF

# --------------------------------------------------------------------------
# 6. Apply patches
# --------------------------------------------------------------------------
echo "==> Applying hid-multitouch patch (0001)..."
# Upstreamed in kernel 7.2+; skip if the source already has MT_CLS_YOGABOOK9I.
pushd "${BUILD_DIR}" >/dev/null
if grep -q "MT_CLS_YOGABOOK9I" hid-multitouch.c; then
    echo "    Already present in upstream source — skipping 0001."
else
    patch -p3 < "${HID_PATCH}"
fi
popd >/dev/null

echo "==> Applying hid-multitouch patch (0002)..."
pushd "${BUILD_DIR}" >/dev/null
patch -p3 < "${HID_PATCH2}"
popd >/dev/null

echo "==> Applying hid-multitouch patch (0003)..."
# Upstreamed in kernel 7.2+; skip if the YOGABOOK9I class entry already has
# MT_QUIRK_CONTACT_CNT_ACCURATE (the key addition of this patch).
pushd "${BUILD_DIR}" >/dev/null
if grep -A 10 "MT_CLS_YOGABOOK9I" hid-multitouch.c | grep -q "MT_QUIRK_CONTACT_CNT_ACCURATE"; then
    echo "    Already present in upstream source — skipping 0003."
else
    patch -p3 < "${HID_PATCH3}"
fi
popd >/dev/null

echo "==> Applying cdc-acm patch (0004)..."
# Upstreamed in kernel 7.0+; skip if the source already has ALWAYS_POLL_CTRL.
pushd "${BUILD_DIR}" >/dev/null
if grep -q "ALWAYS_POLL_CTRL" cdc-acm.c; then
    echo "    Already present in upstream source — skipping 0004."
else
    patch cdc-acm.c < "${CDC_PATCH}"
fi
popd >/dev/null

echo "==> Applying cdc-acm patch (0005)..."
# Upstreamed in kernel 7.2+; skip if the resume path already has the
# tty_port_initialized || ALWAYS_POLL_CTRL bulk-IN start condition.
pushd "${BUILD_DIR}" >/dev/null
if grep -q "tty_port_initialized.*ALWAYS_POLL_CTRL" cdc-acm.c; then
    echo "    Already present in upstream source — skipping 0005."
else
    patch -p4 < "${CDC_PATCH3}"
fi
popd >/dev/null

echo "==> Applying lenovo-ymc patch (0007)..."
# git format-patch: a/drivers/platform/x86/lenovo/ymc.c → strip 5 components
pushd "${BUILD_DIR}" >/dev/null
if grep -q "lenovo_ymc_nosupport_dmi_table" ymc.c; then
    echo "    Already present in upstream source — skipping 0007."
else
    patch -p5 < "${YMC_PATCH}"
fi
popd >/dev/null

# --------------------------------------------------------------------------
# 7. Build
# --------------------------------------------------------------------------
echo "==> Building modules against /usr/src/kernels/${KVER}..."
make -C "/usr/src/kernels/${KVER}" M="${BUILD_DIR}" modules

# --------------------------------------------------------------------------
# 8. Install hid-multitouch
# --------------------------------------------------------------------------
echo "==> Installing hid-multitouch.ko.zst..."
pushd "${BUILD_DIR}" >/dev/null

# Install to updates/ so depmod prefers our version over kernel/'s stock copy.
# This survives kernel-core package reinstalls (which only touch kernel/).
sudo install -d "/lib/modules/${KVER}/updates"
zstd -f -19 hid-multitouch.ko -o hid-multitouch.ko.zst
sudo cp hid-multitouch.ko.zst \
    "/lib/modules/${KVER}/updates/hid-multitouch.ko.zst"
popd >/dev/null

# --------------------------------------------------------------------------
# 9. Install cdc-acm
# --------------------------------------------------------------------------
echo "==> Installing cdc-acm.ko.zst..."
pushd "${BUILD_DIR}" >/dev/null

# Install to updates/ for the same reason as hid-multitouch above.
zstd -f -19 cdc-acm.ko -o cdc-acm.ko.zst
sudo cp cdc-acm.ko.zst \
    "/lib/modules/${KVER}/updates/cdc-acm.ko.zst"
popd >/dev/null

# --------------------------------------------------------------------------
# 10. Install yb9-kbdock
# --------------------------------------------------------------------------
echo "==> Installing yb9-kbdock.ko.zst..."
pushd "${BUILD_DIR}" >/dev/null
sudo install -d "/lib/modules/${KVER}/extra"
zstd -f -19 yb9-kbdock.ko -o yb9-kbdock.ko.zst
sudo cp yb9-kbdock.ko.zst "/lib/modules/${KVER}/extra/yb9-kbdock.ko.zst"
popd >/dev/null

# --------------------------------------------------------------------------
# 10.5. Install lenovo-ymc
# --------------------------------------------------------------------------
echo "==> Installing lenovo-ymc.ko.zst..."
pushd "${BUILD_DIR}" >/dev/null
zstd -f -19 lenovo-ymc.ko -o lenovo-ymc.ko.zst
sudo cp lenovo-ymc.ko.zst "/lib/modules/${KVER}/updates/lenovo-ymc.ko.zst"
popd >/dev/null

# Remove stale extra/ copies — depmod prefers updates/ over extra/ and kernel/.
for mod in hid-multitouch cdc-acm; do
    stale="/lib/modules/${KVER}/extra/${mod}.ko.zst"
    if [ -f "${stale}" ]; then
        echo "==> Removing stale extra/${mod}.ko.zst..."
        sudo rm -f "${stale}"
    fi
done

# --------------------------------------------------------------------------
# 11. Update module dependencies
# --------------------------------------------------------------------------
echo "==> Running depmod -a..."
sudo depmod -a

# --------------------------------------------------------------------------
# 12. Reload modules and re-enumerate INGENIC USB device
# --------------------------------------------------------------------------
echo "==> Reloading modules..."

sudo modprobe -r hid_multitouch 2>/dev/null || true
sudo modprobe hid_multitouch \
    && echo "    hid_multitouch loaded" \
    || echo "    WARNING: hid_multitouch load failed — reboot required"

sudo modprobe -r cdc_acm 2>/dev/null || true
sudo modprobe cdc_acm \
    && echo "    cdc_acm loaded" \
    || echo "    WARNING: cdc_acm load failed — reboot required"

sudo modprobe -r yb9_kbdock lenovo_yb9_kbdock 2>/dev/null || true
sudo modprobe yb9_kbdock \
    && echo "    yb9_kbdock loaded" \
    || echo "    WARNING: yb9_kbdock load failed — reboot required"

# Only reload lenovo_ymc if the unpatched version is currently bound to a
# WMI device.  Reloading the patched version (which returns -ENODEV) is
# unnecessary and triggers a brief rfkill disruption via the ideapad notifier
# chain, temporarily disabling WiFi and Bluetooth.
if ls /sys/bus/wmi/drivers/lenovo-ymc/ 2>/dev/null | grep -qE '^[0-9A-Fa-f]{8}-'; then
    echo "    lenovo_ymc is bound — reloading patched version."
    # Save rfkill state; the unload/load cycle fires the ideapad notifier chain
    # which soft-blocks WiFi and Bluetooth.  Restore immediately after.
    _wifi_up=$(rfkill list type wifi 2>/dev/null | grep -q "Soft blocked: no" && echo yes || echo no)
    _bt_up=$(rfkill list type bluetooth 2>/dev/null | grep -q "Soft blocked: no" && echo yes || echo no)
    sudo modprobe -r lenovo_ymc 2>/dev/null || true
    sudo modprobe lenovo_ymc \
        && echo "    lenovo_ymc loaded (patched)" \
        || echo "    WARNING: lenovo_ymc load failed — reboot required"
    # The ideapad notifier chain fires asynchronously after modprobe returns
    # and may soft-block WiFi/BT up to ~1s later.  Poll until the block
    # actually lands (or 2s passes) before restoring, so we don't restore
    # before the block and then have it re-blocked underneath us.
    for _i in 1 2 3 4; do
        rfkill list type wifi 2>/dev/null | grep -q "Soft blocked: yes" && break
        sleep 0.5
    done
    [ "$_wifi_up" = yes ] && { sudo rfkill unblock wifi 2>/dev/null || true; echo "    WiFi rfkill restored."; }
    [ "$_bt_up"  = yes ] && { sudo rfkill unblock bluetooth 2>/dev/null || true; echo "    Bluetooth rfkill restored."; }
else
    echo "    lenovo_ymc already unbound (patched) — skipping reload."
fi

# Force a full USB re-enumeration of the INGENIC device.  A simple
# modprobe cycle is not enough: the firmware sends a persistent ghost
# contact at probe time that is only cleared by the Input Mode
# SET_REPORT issued during hid-multitouch probe().  That SET_REPORT
# only reaches the firmware if it arrives as part of a fresh USB
# enumeration sequence (deauthorize → reauthorize triggers a USB reset
# and a new enumeration, after which probe() runs from scratch).
echo "==> Re-enumerating INGENIC USB device to flush firmware ghost contact..."
INGENIC_USB=""
for idv in /sys/bus/usb/devices/*/idVendor; do
    d="$(dirname "$idv")"
    if [ "$(cat "$d/idVendor" 2>/dev/null)" = "17ef" ] && \
       [ "$(cat "$d/idProduct" 2>/dev/null)" = "6161" ]; then
        INGENIC_USB="$d"
        break
    fi
done
if [ -n "$INGENIC_USB" ]; then
    echo "    Device: ${INGENIC_USB##*/}"
    echo 0 | sudo tee "$INGENIC_USB/authorized" >/dev/null
    sleep 1
    echo 1 | sudo tee "$INGENIC_USB/authorized" >/dev/null
    sleep 2
    echo "    Re-enumeration complete."
else
    echo "    WARNING: INGENIC 17EF:6161 USB device not found — reboot to clear ghost contact"
fi

# --------------------------------------------------------------------------
# 13. Restart touchpad daemon
# --------------------------------------------------------------------------
# When running under sudo, systemctl --user targets root's (non-graphical)
# session.  Use SUDO_USER + XDG_RUNTIME_DIR to reach the actual user's bus.
_SC_USER="${SUDO_USER:-${USER}}"
_SC_UID="$(id -u "${_SC_USER}" 2>/dev/null || echo "")"
_sc() { XDG_RUNTIME_DIR="/run/user/${_SC_UID}" sudo -u "${_SC_USER}" systemctl --user "$@"; }

if _sc cat plasma-touchpad.service &>/dev/null; then
    echo "==> Restarting plasma-touchpad-daemon via systemd (user: ${_SC_USER})..."
    _sc restart plasma-touchpad.service
    sleep 0.5
    if _sc is-active --quiet plasma-touchpad.service; then
        echo "    plasma-touchpad.service active"
    else
        echo "    WARNING: plasma-touchpad.service failed to start"
        _sc status plasma-touchpad.service --no-pager || true
    fi
else
    echo "    Skipping daemon restart: plasma-touchpad.service not found"
fi

# --------------------------------------------------------------------------
# 14. Unbind/rebind hid-multitouch for INGENIC device to clear ghost state
# --------------------------------------------------------------------------
echo "==> Clearing ghost state: unbinding hid-multitouch from INGENIC device..."
# Find the hid-multitouch-bound device entry for 17EF:6161
HID_MT_DEV=$(ls /sys/bus/hid/drivers/hid-multitouch/ 2>/dev/null \
    | grep -i "17EF:6161" | head -1)

if [ -n "$HID_MT_DEV" ]; then
    echo "    Device: ${HID_MT_DEV}"
    echo "${HID_MT_DEV}" | sudo tee /sys/bus/hid/drivers/hid-multitouch/unbind >/dev/null
    sleep 1
    echo "${HID_MT_DEV}" | sudo tee /sys/bus/hid/drivers/hid-multitouch/bind >/dev/null
    sleep 1
    echo "    Ghost state cleared."
else
    echo "    WARNING: INGENIC hid-multitouch device not found; ghost state not cleared"
fi

# --------------------------------------------------------------------------
# 15. Screen rotation setup
# --------------------------------------------------------------------------
ROTATION_DIR="${REPO_DIR}/rotation"
echo "==> Installing screen rotation daemon and rules..."

if [ -f "${ROTATION_DIR}/61-sensor-yogabook9.rules" ]; then
    sudo cp "${ROTATION_DIR}/61-sensor-yogabook9.rules" /etc/udev/rules.d/
    sudo udevadm control --reload-rules
    sudo udevadm trigger --action=add --subsystem-match=iio
    sudo systemctl restart iio-sensor-proxy.service
    echo "    Udev rules installed and iio-sensor-proxy restarted."
else
    echo "    WARNING: 61-sensor-yogabook9.rules not found at ${ROTATION_DIR}/ — skipping"
fi

if [ -f "${ROTATION_DIR}/51-sensor-proxy-yoga9.rules" ]; then
    sudo cp "${ROTATION_DIR}/51-sensor-proxy-yoga9.rules" /etc/polkit-1/rules.d/
    echo "    Polkit rule installed."
fi

if [ -f "${ROTATION_DIR}/yoga9-rotate.py" ]; then
    sudo cp "${ROTATION_DIR}/yoga9-rotate.py" /usr/local/bin/yoga9-rotate.py
    sudo chmod 755 /usr/local/bin/yoga9-rotate.py
    echo "    Daemon installed at /usr/local/bin/yoga9-rotate.py"
fi

if [ -f "${ROTATION_DIR}/screen-rotate.service" ]; then
    sudo cp "${ROTATION_DIR}/screen-rotate.service" /etc/systemd/system/screen-rotate.service
    sudo systemctl daemon-reload
    if systemctl is-enabled --quiet screen-rotate.service 2>/dev/null; then
        sudo systemctl restart screen-rotate.service \
            && echo "    screen-rotate.service restarted." \
            || echo "    WARNING: screen-rotate.service failed to restart"
    else
        sudo systemctl enable --now screen-rotate.service \
            && echo "    screen-rotate.service enabled and started." \
            || echo "    WARNING: screen-rotate.service failed to start"
    fi
fi

# --------------------------------------------------------------------------
echo ""
echo "==> Done. Patches installed and loaded for ${KVER}."
